# Enactic v2 manifest.
_ANVIL_ARM_VELOCITY_LIMIT: float = 4.0
_ANVIL_GRIPPER_VELOCITY_LIMIT: float = 4.0


def _anvil_arm_joint_specs(
    names: tuple[str, ...],
    position_limits: dict[str, tuple[float, float]],
    side: str,
) -> list[JointSpec]:
    # Body chain in the v2-era MJCF: base_link → link1..link6 → ee_base_link.
    parents = [f"openarm_{side}_base_link"] + [f"openarm_{side}_link{i}" for i in range(1, 7)]
    children = [f"openarm_{side}_link{i}" for i in range(1, 7)] + [f"openarm_{side}_ee_base_link"]
    return [
        JointSpec(
            name=name,
            joint_type=JointType.REVOLUTE,
            parent_link=parent,
            child_link=child,
            position_limits=position_limits[name],
            velocity_limit=_ANVIL_ARM_VELOCITY_LIMIT,
            effort_limit=_ANVIL_ARM_EFFORT_LIMITS[name],
            has_torque_sensor=True,
            actuator_kind="bldc",
            # The MJCF qualifies the logical joint with the ``openarm_``
            # prefix (must match robots/anvil_openarm_v2/robot.yaml).
            sim_joint_name=f"openarm_{name}",
        )
        for name, parent, child in zip(names, parents, children, strict=True)
    ]


def _anvil_gripper_joint_spec(
    name: str, side: str, position_limits: tuple[float, float]
) -> JointSpec:
    # The public gripper channel drives ``finger_joint1`` (the inner
    # finger); the outer finger follows via the MJCF ``<equality>``.
    return JointSpec(
        name=name,
        joint_type=JointType.REVOLUTE,  # v2-era grippers are hinge jaws
        parent_link=f"openarm_{side}_ee_base_link",
        child_link=f"openarm_{side}_ee_inner_finger",
        position_limits=position_limits,
        velocity_limit=_ANVIL_GRIPPER_VELOCITY_LIMIT,
        effort_limit=_ANVIL_GRIPPER_EFFORT_LIMIT,
        has_torque_sensor=False,
        actuator_kind="servo",
        role="gripper",
    )


def _anvil_joint_specs() -> list[JointSpec]:
    return [
        *_anvil_arm_joint_specs(_ANVIL_LEFT_ARM_JOINTS, _ANVIL_LEFT_ARM_POSITION_LIMITS, "left"),
        _anvil_gripper_joint_spec(
            _ANVIL_LEFT_GRIPPER_JOINT, "left", _ANVIL_LEFT_GRIPPER_POSITION_LIMITS
        ),
        *_anvil_arm_joint_specs(_ANVIL_RIGHT_ARM_JOINTS, _ANVIL_RIGHT_ARM_POSITION_LIMITS, "right"),
        _anvil_gripper_joint_spec(
            _ANVIL_RIGHT_GRIPPER_JOINT, "right", _ANVIL_RIGHT_GRIPPER_POSITION_LIMITS
        ),
    ]



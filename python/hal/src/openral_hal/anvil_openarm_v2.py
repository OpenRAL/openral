# ── HAL ──────────────────────────────────────────────────────────────────────


class AnvilOpenArmV2MujocoHAL(MujocoArmHAL):
    """HAL adapter for the Anvil OpenARM 2.0 (MuJoCo digital twin).

    Thin manifest-driven wrapper around :class:`MujocoArmHAL`, exactly
    like the Enactic v2 adapter: the MJCF ships native ``<position>``
    actuators with per-class PD gains, so all wiring (the
    ``openarm:anvil_v2_bimanual`` MJCF ref, the joint→qpos map that skips
    the follower fingers, two ``PASSTHROUGH`` hinge grippers,
    ``seed_ctrl_from_qpos``) lives in
    :data:`ANVIL_OPENARM_V2_DESCRIPTION.sim` (ADR-0023).

    What makes it the *Anvil* 2.0 rather than the stock v2 arm is
    entirely in the fetched MJCF: J1 clamped to +/-135 deg, J6 widened
    to -45..+70 deg of radial deviation, and the wrist support bracket
    (visual-only) that enables it — see
    :mod:`openral_hal._anvil_openarm_v2_assets`.

    Args:
        mjcf_path: Optional override for the MJCF file path.  When
            ``None``, the Anvil 2.0 bimanual MJCF is fetched lazily
            through ``ensure_anvil_openarm_v2_mjcf`` via the
            ``openarm:anvil_v2_bimanual`` URI scheme.
        settle_steps: Number of MuJoCo physics steps performed in
            :meth:`send_action`.
        gravity_enabled: When ``False``, gravity is zeroed at
            ``connect()`` time for deterministic closed-loop tests.
        staleness_limit_s: Maximum age of a cached state.

    Example:
        >>> from openral_hal import AnvilOpenArmV2MujocoHAL  # doctest: +SKIP
        >>> hal = AnvilOpenArmV2MujocoHAL(gravity_enabled=False)  # doctest: +SKIP
        >>> hal.connect()  # doctest: +SKIP
        >>> state = hal.read_state()  # doctest: +SKIP
        >>> len(state.position)  # 7 + 1 + 7 + 1  # doctest: +SKIP
        16
        >>> hal.disconnect()  # doctest: +SKIP
    """

    def __init__(
        self,
        *,
        mjcf_path: str | None = None,
        settle_steps: int = 1,
        gravity_enabled: bool = True,
        staleness_limit_s: float = 0.5,
    ) -> None:
        """Initialise the adapter; the MJCF is not loaded until ``connect()``."""
        self._init_from_description(
            ANVIL_OPENARM_V2_DESCRIPTION,
            mjcf_path=mjcf_path,
            settle_steps=settle_steps,
            gravity_enabled=gravity_enabled,
            staleness_limit_s=staleness_limit_s,
        )

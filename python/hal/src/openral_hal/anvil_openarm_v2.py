"""HAL adapter for the Anvil OpenARM 2.0 bimanual arm (MuJoCo digital twin).

The Anvil OpenARM 2.0 (https://docs.anvil.bot/introduction/openarm-2.0)
is Anvil Robotics' manufactured variant of the standard OpenArm v2.
The 2.0 generation carries the OpenARM 2.0 wrist swap (J6 = radial /
ulnar deviation, J7 = flexion / extension — flipped relative to
OpenArm 1.0), and the Anvil variant differs from the standard v2 in
exactly two documented joint ranges plus one part:

* **J1: +/-135 deg** (standard v2 ships -200..+80 deg in the MJCF sign
  convention) — symmetric base yaw on both arms.
* **J6: -45..+70 deg** (standard v2: +/-45 deg) — the extra +25 deg of
  radial deviation enabled by Anvil's wrist support bracket.
* **The wrist support bracket** — clamps the J6 rotor hub and lands on a
  plate bolted to the J7 motor end cap; represented in the MJCF by
  visual-only STL meshes from the hardware CAD, hosted on the ``link5``
  forearm bodies (the bracket must not rotate with J6).

Everything else — kinematics, meshes, native ``<position>`` actuators
with per-class PD gains, the single-driven-finger grippers with the
``<equality>``-coupled follower — is the upstream Enactic OpenArm v2.
The MJCF is generated by ``bensonlee5/anvil-openarm-mujoco`` (upstream
v2 files + the Anvil deltas, validated against the docs' numeric
comparison table) and fetched at a pinned SHA by
:mod:`openral_hal._anvil_openarm_v2_assets` via the
``openarm:anvil_v2_bimanual`` asset ref.

Like the Enactic v2 adapter (:mod:`openral_hal.openarm`) this is a thin
manifest-driven :class:`MujocoArmHAL` subclass (ADR-0023): the MJCF's
own PD law handles dynamics, ``send_action`` writes target → ctrl.

Action layout
-------------
16-DoF :class:`openral_core.Action`, same slot order as the Enactic
v2 adapter:

* ``target[0:7]``   — left arm joints (radians)
* ``target[7]``     — left gripper jaw (rad, ``[0, 0.7854]``)
* ``target[8:15]``  — right arm joints (radians)
* ``target[15]``    — right gripper jaw (rad, ``[-0.7854, 0]``)

Gripper ranges mirror in sign across the centreline exactly as on the
Enactic v2 arm.  J2 keeps the v2 mirrored asymmetry; J1 and J6 carry
the Anvil ranges (identical numerics on both arms — upstream encodes
the mirror as flipped axes).

Example:
    >>> from openral_hal import AnvilOpenArmV2MujocoHAL, ANVIL_OPENARM_V2_DESCRIPTION
    >>> hal = AnvilOpenArmV2MujocoHAL(gravity_enabled=False)  # doctest: +SKIP
    >>> hal.connect()  # doctest: +SKIP
    >>> state = hal.read_state()  # doctest: +SKIP
    >>> len(state.position) == len(ANVIL_OPENARM_V2_DESCRIPTION.joints) == 16  # doctest: +SKIP
    True
    >>> hal.disconnect()  # doctest: +SKIP
"""


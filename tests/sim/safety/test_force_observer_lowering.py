"""The OpenArm's ``force_observer`` block is exactly what its MJCF lowers to (issue #373).

``robots/openarm/robot.yaml`` carries the kernel observer's inertials and joint
terms, generated by ``tools/lower_force_observer.py``. The lowering also proves
the manifest's link frames are the MJCF's (it refuses otherwise), so this test
fails both on a hand edit of the block and on a manifest frame change that
leaves the inertials in the wrong place. Also checks the folded mass equals the
MJCF's arm bodies, so nothing was dropped or double-counted.
"""

from __future__ import annotations

import pathlib

import pytest

mujoco = pytest.importorskip("mujoco", reason="MuJoCo not installed (sim extra)")

from openral_core import RobotDescription  # noqa: E402
from openral_core.assets import resolve_asset  # noqa: E402
from openral_safety.dynamics_lowering import lower_force_observer_from_mjcf  # noqa: E402

_MANIFEST = pathlib.Path(__file__).resolve().parents[3] / "robots" / "openarm" / "robot.yaml"


def test_openarm_force_observer_block_matches_its_mjcf() -> None:
    robot = RobotDescription.from_yaml(str(_MANIFEST))
    assert robot.force_observer is not None
    lowered = lower_force_observer_from_mjcf(robot, manifest_dir=_MANIFEST.parent)
    assert lowered == robot.force_observer, (
        "robots/openarm/robot.yaml force_observer drifted from its MJCF; regenerate it with "
        "tools/lower_force_observer.py"
    )

    assert robot.assets.mjcf is not None
    mjcf = resolve_asset(robot.assets.mjcf, "mjcf", manifest_dir=_MANIFEST.parent)
    assert mjcf is not None
    model = mujoco.MjModel.from_xml_path(str(mjcf))
    total = sum(x.mass_kg for x in robot.force_observer.links)
    assert total == pytest.approx(float(model.body_subtreemass[0]), rel=1e-6)
